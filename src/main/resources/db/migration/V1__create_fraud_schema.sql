-- Categorised transaction events received for assessment.
create table transaction_event (
    id                   bigint generated by default as identity primary key,
    transaction_id       varchar(64)    not null,
    policy_number        varchar(40)    not null,
    account_id           varchar(40)    not null,
    payee_account_id     varchar(40)    not null,
    category             varchar(40)    not null,
    amount               numeric(15, 2) not null,
    occurred_at          timestamp with time zone not null,
    claim_reference      varchar(64),
    policy_inception_date date,
    received_at          timestamp with time zone not null,
    constraint uk_transaction_event_transaction_id unique (transaction_id)
);

create index idx_transaction_event_policy_occurred on transaction_event (policy_number, occurred_at);

-- One fraud assessment per transaction event (1:1).
create table fraud_assessment (
    id                   uuid primary key,
    transaction_event_id bigint      not null unique references transaction_event (id),
    risk_score           integer     not null,
    risk_level           varchar(10) not null,
    decision             varchar(40) not null,
    rules_version        varchar(20) not null,
    evaluated_at         timestamp with time zone not null
);

create index idx_fraud_assessment_decision_evaluated on fraud_assessment (decision, evaluated_at);
create index idx_fraud_assessment_level_evaluated on fraud_assessment (risk_level, evaluated_at);

-- Rules that fired for an assessment, in evaluation order.
create table fraud_assessment_rule (
    assessment_id uuid         not null references fraud_assessment (id),
    rule_order    integer      not null,
    rule_code     varchar(60)  not null,
    weight        integer      not null,
    reason        varchar(500) not null,
    primary key (assessment_id, rule_order)
);
